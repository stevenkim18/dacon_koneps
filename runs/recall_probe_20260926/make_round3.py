"""09-27 R14(3차 표현 보강) — 보류 세트 H2에서 남은 누락을 막는다. R1~R13이 들어간 판(scope_recall_plus, s26_recall_plus)에 얹는다.
무라벨 20,000 문형 빈도(09-27 새벽): v1 학회·협회에 한하여 0 · 연합회 회원 머리말 0 · 대학·연구소에 한함 0 · v21 '지분율 하한' 0 ·
v2 'N회 이상 수행한 업체' 0 · 지역 '사업장이 ○○ 내에 있는'(기존 문형과 겹침). 편집 문장에만 켜지는 무비용 보강이 목표다.

사용: make_round3.py SRC.py DST.py
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf-8").read()


def sub(old, new):
    global s
    assert s.count(old) == 1, (s.count(old), old[:90])
    s = s.replace(old, new)


# v1: '사단법인 ○○학회에 한하여 입찰 참여 가능', '국립대학교 또는 그 부설 연구소에 한함'
sub(r'''                              r"(에|으로|로)\s*한하여\s*(입찰에?\s*)?(참가|참여|응찰)")''',
    r'''                              r"(에|으로|로)\s*한하여\s*(입찰에?\s*)?(참가|참여|응찰)"
                              r"|(학회|협회|연합회)\s*(에|으로|로)\s*한하여\s*(입찰에?\s*)?(참가|참여|응찰)"
                              r"|(대학교?|연구소|연구\s*기관|산학\s*협력단)\s*(에|으로|로)\s*한함")''')
# v1: 자격 머리말 '입찰참가자격: ○○연합회 회원사'
sub(r'''                          r"|참가\s*자격\s*[:：][^\n]{0,30}(협회|학회)\s*(의\s*)?(정\s*)?회원")''',
    r'''                          r"|참가\s*자격\s*[:：][^\n]{0,30}(협회|학회|연합회)\s*(의\s*)?(정\s*)?회원")''')
# 지역: '사업장이 전라북도 내에 있는 업체로 한정'
sub(r'''                           r"|주\s*사무소를?\s*(둔|두고)|소재\s*법인|소재하는\s*(업체|사업자|자|법인)"''',
    r'''                           r"|주\s*사무소를?\s*(둔|두고)|소재\s*법인|소재하는\s*(업체|사업자|자|법인)"
                           r"|사업장이\s*[^\n]{0,30}(내에|관내에)\s*(있는|소재)"''')
# v21: '공동수급체 구성원별 지분율 하한: 3%'
sub(r'''        r"(최소\s*(참여)?\s*지분(율|비율)?|지분(율|비율)?[^\n]{0,15}최소)[^\n%]{0,25}?(\d+(\.\d+)?)\s*(%|퍼센트)", src)]''',
    r'''        r"(최소\s*(참여)?\s*지분(율|비율)?|지분(율|비율)?[^\n]{0,15}(?:최소|하한))[^\n%]{0,25}?(\d+(\.\d+)?)\s*(%|퍼센트)", src)]''')
# v2: '동일 분야 사업을 최근 5년 동안 3회 이상 수행한 업체'('실적' 낱말 없음)
sub(r'''                         r"|(운영|공급|대행|시공)\s*경험이\s*있는|(이행|수행|납품|공급)\s*(을\s*)?(완료)?\s*한\s*사실이\s*있는"):''',
    r'''                         r"|(운영|공급|대행|시공)\s*경험이\s*있는|(이행|수행|납품|공급)\s*(을\s*)?(완료)?\s*한\s*사실이\s*있는"
                         r"|\d+\s*(회|건)\s*이상\s*(수행|납품|공급|운영)한\s*(업체|자)"):''')

open(dst, "w", encoding="utf-8").write(s)
print("wrote", dst)
